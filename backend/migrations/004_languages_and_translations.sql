-- ------------------------------------------------------------ the strings

-- Everything the app itself says is a key here, with its English and its
-- Slovak string: the top bar, the home page, every page of the kanji area and
-- of the exam, the pages drawn when the app cannot run. Not here, and never
-- translated: the study material (the kanji, the words, their readings and
-- English glosses, the exam's questions) and the names of the SRS stages
-- ("Apprentice", "Guru"...), which are terms. The owner's two pages,
-- Translations and Languages, are English and written in their templates.
--
-- The code names a key and the page shows its string; a key with no string
-- shows as the key itself, on purpose, so a gap is seen. The list below and
-- the frontend are held together by a test (tests/unit/translations.test.php):
-- every key the frontend asks for is here, and every key here is asked for.
--
-- The description is all a translator has: where the string is shown and
-- what its {placeholders} stand for. The English string fixes which
-- placeholders a key has (the code fills exactly those), so English may be
-- reworded in the browser but never gain or lose one, and another language
-- may use only those.
--
-- Keys ending in .one, .few and .other are the forms of one plural, asked for
-- by the family's name with a {count}: Slovak says "1 otázka", "3 otázky",
-- "12 otázok". English never picks .few; it says there what .other says,
-- because it is what a language with no string of its own falls back to.
-- Slovak speaks to the learner informally here (ty), as the other anotoki
-- sites do.
--
-- Every insert steps aside for a row that is already there: a string reworded
-- in the browser is the owner's and is never written over. So a string added
-- or reworded after this is a migration of its own, never an edit of this
-- file. One string on a line, an apostrophe written twice and nothing else
-- escaped.

