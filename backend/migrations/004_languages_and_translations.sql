-- 004 — the app's own words, in more than one language (2026-09-30)
--
-- What Japanese Academy itself says — its buttons, its headings, "3 reviews
-- due" — becomes translatable: English and Slovak to begin with. The study
-- material is another matter and is never translated: the kanji, the words,
-- their readings and English glosses, the exam's questions.
--
-- The words are rows rather than files in the build because the owner rewords
-- them in the browser: a file in the Angular build is overwritten by the next
-- upload, and a hosted site has no shell to edit one with. So a string is a
-- key the code names, and a value per language that the owner may reword.
--   languages          the languages the app is offered in
--   translation_keys   the keys, each with a note for whoever translates it
--   translations       one string: a key in a language
--
-- Which keys there are is the code's business: migrations write them (this
-- one, and one for every string added later), the owner's pages only ever
-- change values. That is why a key has no "created by", and why a value
-- written by a migration has nobody in updated_by.
--
-- English is what every other language falls back to, string by string, so
-- it is always here and always on. There is no flag for HTML on a string and
-- no such thing in the app: a string is text, and is drawn as text.
--
-- These three tables are the site's, not a person's: everybody reads them,
-- the owner writes them, and they are no part of anybody's study data
-- (backend/src/translations.php). This file makes and fills them and touches
-- no other table. Every insert steps aside for a row that is already there.

-- -------------------------------------------------------------- languages

-- A code is what a browser and the IAM's token call the language ("sk",
-- "pt-br": always small letters here); the names are for people: name in
-- English for the owner's pages, native_name for the chooser a learner sees.
-- A language switched off is no longer offered, and keeps its strings.
CREATE TABLE languages (
    code        varchar(10) PRIMARY KEY CHECK (code ~ '^[a-z]{2}(-[a-z]{2})?$'),
    name        varchar(50) NOT NULL,              -- in English: "Slovak"
    native_name varchar(50) NOT NULL,              -- as its speakers write it: "Slovenčina"
    enabled     boolean     NOT NULL DEFAULT true,
    sort_order  integer     NOT NULL DEFAULT 0
);

-- ------------------------------------------------------- translation_keys

-- description: where the string is shown and what its {placeholders} stand
-- for; all a translator has to go by.
CREATE TABLE translation_keys (
    name        varchar(200) PRIMARY KEY,
    description text,
    created_at  timestamptz  NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------- translations

-- One string: a key in a language. There is no empty one: a language that
-- has no string for a key has no row, and reads the English. updated_by is
-- who last reworded it in the browser (null: as a migration wrote it). It
-- follows a person whose user id changes (backend/src/owner.php) and empties
-- when their row goes, so nobody's leaving ever takes a string along.
CREATE TABLE translations (
    key_name      varchar(200) NOT NULL REFERENCES translation_keys (name) ON UPDATE CASCADE ON DELETE CASCADE,
    language_code varchar(10)  NOT NULL REFERENCES languages (code) ON UPDATE CASCADE ON DELETE CASCADE,
    value         text         NOT NULL CHECK (value <> ''),
    updated_at    timestamptz  NOT NULL DEFAULT now(),
    updated_by    bigint       REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    PRIMARY KEY (key_name, language_code)
);

